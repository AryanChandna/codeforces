#!/usr/bin/env python3
"""Writes a Codeforces submission log as a comment block at the top of src/P<id>.java.

Usage:
  python3 scripts/cflog.py 228A        # update one file
  python3 scripts/cflog.py --all       # update every src/P*.java

Every submission for the problem by HANDLE is listed (newest first), whatever
the verdict. The block sits between the BEGIN/END markers and is replaced on
each run, so it is safe to re-run.
"""
import datetime
import glob
import json
import os
import re
import sys
import urllib.request

HANDLE = "aryanchandna02"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "// ===== Codeforces submissions (auto-generated by scripts/cflog.py) ====="
END = "// ======================================================================="

VERDICTS = {
    "OK": "Accepted",
    "WRONG_ANSWER": "Wrong answer",
    "TIME_LIMIT_EXCEEDED": "Time limit exceeded",
    "MEMORY_LIMIT_EXCEEDED": "Memory limit exceeded",
    "RUNTIME_ERROR": "Runtime error",
    "COMPILATION_ERROR": "Compilation error",
    "IDLENESS_LIMIT_EXCEEDED": "Idleness limit exceeded",
    "TESTING": "Testing",
}


def fetch_submissions():
    url = f"https://codeforces.com/api/user.status?handle={HANDLE}"
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    if data.get("status") != "OK":
        sys.exit(f"Codeforces API error: {data.get('comment')}")
    return data["result"]


def problem_names():
    names = {}
    with open(os.path.join(ROOT, "problems.tsv")) as f:
        for line in f:
            _, pid, _, name = line.rstrip("\n").split("\t")
            names[pid] = name
    return names


def verdict_text(s):
    v = s.get("verdict", "TESTING")
    text = VERDICTS.get(v, v.replace("_", " ").capitalize())
    if v not in ("OK", "COMPILATION_ERROR", "TESTING"):
        text += f" on test {s.get('passedTestCount', 0) + 1}"
    return text


def build_block(pid, subs, name):
    c, idx = re.match(r"(\d+)(\w+)", pid).groups()
    lines = [
        BEGIN,
        f"// {pid} - {name}",
        f"// Problem: https://codeforces.com/problemset/problem/{c}/{idx}",
    ]
    if not subs:
        lines.append("// No submissions yet.")
    for s in subs:
        when = datetime.datetime.fromtimestamp(s["creationTimeSeconds"]).strftime("%Y-%m-%d %H:%M")
        lines.append(
            f"// {when}  {verdict_text(s):<28} {s['timeConsumedMillis']:>5} ms "
            f"{s['memoryConsumedBytes'] // 1024:>7} KB  {s['programmingLanguage']}"
            f"  https://codeforces.com/contest/{c}/submission/{s['id']}"
        )
    lines.append(END)
    return "\n".join(lines) + "\n"


def update_file(path, pid, all_subs, names):
    subs = [s for s in all_subs
            if f"{s['problem'].get('contestId')}{s['problem']['index']}" == pid]
    with open(path) as f:
        src = f.read()
    # drop any existing block, then prepend the fresh one
    src = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n\n?", "", src, flags=re.S)
    with open(path, "w") as f:
        f.write(build_block(pid, subs, names.get(pid, "?")) + "\n" + src)
    best = next((verdict_text(s) for s in subs), "no submissions")
    print(f"P{pid}: {len(subs)} submission(s), latest: {best}")


def main():
    args = sys.argv[1:]
    if not args:
        sys.exit(__doc__)
    all_subs, names = fetch_submissions(), problem_names()
    if args == ["--all"]:
        paths = sorted(glob.glob(os.path.join(ROOT, "src", "P*.java")))
    else:
        paths = [os.path.join(ROOT, "src", f"P{a.upper()}.java") for a in args]
    for p in paths:
        pid = os.path.basename(p)[1:-5]
        if not os.path.exists(p):
            print(f"skip {pid}: {p} not found")
            continue
        update_file(p, pid, all_subs, names)


if __name__ == "__main__":
    main()
